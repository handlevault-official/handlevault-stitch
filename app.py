DMC = []
for chunk in DMC_RAW.replace("\n", "|").split("|"):
    p = chunk.split()
    DMC.append((p[0], tuple(int(x) for x in p[1:4])))
SYMBOLS = list("ABCDEFGHJKLMNPQRSTUVWXYZabdefghkmnqrty23456789#@%&*+=?/<>~^$")

def _lab(rgb):
    a = np.asarray(rgb, float) / 255.0
    a = np.where(a > 0.04045, ((a + 0.055) / 1.055) ** 2.4, a / 12.92)
    m = np.array([[.4124, .3576, .1805], [.2126, .7152, .0722], [.0193, .1192, .9505]])
    xyz = a @ m.T / np.array([.95047, 1, 1.08883])
    f = np.where(xyz > .008856, np.cbrt(xyz), 7.787 * xyz + 16 / 116)
    return np.stack([116 * f[..., 1] - 16, 500 * (f[..., 0] - f[..., 1]), 200 * (f[..., 1] - f[..., 2])], -1)

DMC_LAB = _lab([c for _, c in DMC])

def make_pattern(data, width=80, colors=20):
    img = ImageOps.exif_transpose(Image.open(io.BytesIO(data)))
    if img.mode in ("RGBA", "LA", "P"):
        img = img.convert("RGBA")
        bg = Image.new("RGBA", img.size, (255, 255, 255, 255)); bg.alpha_composite(img); img = bg
    img = img.convert("RGB")
    h = max(1, round(img.height * width / img.width))
    img = img.resize((width, h), Image.LANCZOS)
    q = np.array(img.quantize(colors=colors, method=Image.MEDIANCUT, dither=Image.NONE).convert("RGB"))
    uniq, inv = np.unique(q.reshape(-1, 3), axis=0, return_inverse=True)
    d = ((_lab(uniq)[:, None, :] - DMC_LAB[None, :, :]) ** 2).sum(-1)
    dmc_idx = d.argmin(1)[inv.reshape(-1)].reshape(h, width)
    ids, counts = np.unique(dmc_idx, return_counts=True)
    order = ids[np.argsort(-counts)]
    legend, remap = [], {}
    for n, i in enumerate(order):
        remap[i] = n
        legend.append(dict(code=DMC[i][0], rgb=DMC[i][1], sym=SYMBOLS[n % len(SYMBOLS)],
                           count=int(counts[list(ids).index(i)])))
    grid = np.vectorize(remap.get)(dmc_idx)
    return grid, legend

def build_pdf(grid, legend, fabric=14, title="Cross-Stitch Pattern"):
    H, W = grid.shape
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A4)
    c.setTitle(title)
    PW, PH = A4
    # ---- cover ----
    c.setFont("Helvetica-Bold", 22); c.drawString(40, PH - 60, title)
    c.setFont("Helvetica", 10)
    fw, fh = W / fabric, H / fabric
    c.drawString(40, PH - 80, f"{W} x {H} stitches  |  {fabric}-count Aida  |  design {fw:.1f} x {fh:.1f} in "
                              f"({fw*2.54:.1f} x {fh*2.54:.1f} cm)  |  suggested fabric {fw+6:.0f} x {fh+6:.0f} in")
    c.drawString(40, PH - 94, f"{len(legend)} thread colors (DMC)  |  Generated by Handle Vault Stitch")
    pal = np.array([l["rgb"] for l in legend], np.uint8)
    prev = Image.fromarray(pal[grid]).resize((W * 6, H * 6), Image.NEAREST)
    mw, mh = PW - 80, 330
    s = min(mw / prev.width, mh / prev.height)
    c.drawImage(ImageReader(prev), 40, PH - 110 - prev.height * s, prev.width * s, prev.height * s)
    y = PH - 130 - prev.height * s

    def head(y):
        c.setFont("Helvetica-Bold", 9)
        c.drawString(40, y, "Swatch"); c.drawString(90, y, "Symbol"); c.drawString(140, y, "DMC")
        c.drawString(210, y, "Stitches"); c.drawString(280, y, "Skeins (est.)")
        return y - 16
    y = head(y)
    c.setFont("Helvetica", 10)
    per_skein = 1600 * fabric / 14  # rough, 2 strands
    for l in legend:
        if y < 50:
            c.showPage(); y = head(PH - 50); c.setFont("Helvetica", 10)
        c.setFillColorRGB(*[v / 255 for v in l["rgb"]]); c.rect(40, y - 3, 35, 12, fill=1, stroke=1)
        c.setFillColorRGB(0, 0, 0)
        c.drawString(98, y, l["sym"]); c.drawString(140, y, l["code"])
        c.drawString(210, y, str(l["count"])); c.drawString(280, y, str(max(1, math.ceil(l["count"] / per_skein))))
        y -= 17
    c.showPage()
    # ---- chart tiles ----
    CS, TC, TR = 10, 50, 70
    left, top = (PW - TC * CS) / 2, PH - 55
    tiles = [(r, k) for r in range(0, H, TR) for k in range(0, W, TC)]
    for n, (r0, c0) in enumerate(tiles, 1):
        r1, c1 = min(r0 + TR, H), min(c0 + TC, W)
        for r in range(r0, r1):
            for k in range(c0, c1):
                l = legend[grid[r, k]]
                x, yy = left + (k - c0) * CS, top - (r - r0 + 1) * CS
                c.setFillColorRGB(*[1 - (1 - v / 255) * .35 for v in l["rgb"]])
                c.setStrokeColorRGB(.7, .7, .7); c.setLineWidth(.25)
                c.rect(x, yy, CS, CS, fill=1, stroke=1)
                c.setFillColorRGB(0, 0, 0); c.setFont("Helvetica", 7)
                c.drawCentredString(x + CS / 2, yy + 2.6, l["sym"])
        c.setStrokeColorRGB(0, 0, 0); c.setLineWidth(1); c.setFont("Helvetica", 6)
        for k in range(c0, c1 + 1):
            if k % 10 == 0:
                x = left + (k - c0) * CS
                c.line(x, top, x, top - (r1 - r0) * CS); c.drawCentredString(x, top + 4, str(k))
        for r in range(r0, r1 + 1):
            if r % 10 == 0:
                yy = top - (r - r0) * CS
                c.line(left, yy, left + (c1 - c0) * CS, yy); c.drawRightString(left - 3, yy - 2, str(r))
        c.setFont("Helvetica", 8)
        c.drawString(left, 25, f"Page {n}/{len(tiles)}  -  columns {c0+1}-{c1}, rows {r0+1}-{r1}  -  centre = (col {W//2}, row {H//2})")
        c.showPage()
    c.save()
    return buf.getvalue()
